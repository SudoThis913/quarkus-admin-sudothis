-- Clean slate for the new "Compliance-First" schema

CREATE TABLE APP_USER (
    id BIGINT NOT NULL AUTO_INCREMENT,
    USERNAME VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(255),
    KEYCLOAK_SUB VARCHAR(255) UNIQUE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE AUDIT_LOG (
    id BIGINT NOT NULL AUTO_INCREMENT,
    ACTOR_ID VARCHAR(255), -- Keycloak Sub or Username (since strictly local IDs might not exist for admin)
    ACTION VARCHAR(64) NOT NULL,
    TARGET_TABLE VARCHAR(64) NOT NULL,
    TARGET_ID VARCHAR(255),
    PAYLOAD JSON,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
) ENGINE=InnoDB;

-- Create an index for performance
CREATE INDEX idx_audit_target ON AUDIT_LOG(TARGET_TABLE, TARGET_ID);
CREATE INDEX idx_audit_actor ON AUDIT_LOG(ACTOR_ID);
